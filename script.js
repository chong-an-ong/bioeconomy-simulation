/* =========================================================
   COALITION MODAL
   ========================================================= */

function openCoalition(filterType, filterValue) {

  const matchingActors = [];

Object.entries(delegations).forEach(
  ([country, delegation]) => {

    // Check lead negotiator
    const leadTags =
      delegation.lead[
        filterType === "sector"
          ? "sectors"
          : "constituencies"
      ] || [];

    if (leadTags.includes(filterValue)) {

      matchingActors.push({
        country,
        actor: delegation.lead
      });

    }

    // Check subnational actors
    delegation.actors.forEach(actor => {

      const tags =
        actor[
          filterType === "sector"
            ? "sectors"
            : "constituencies"
        ] || [];

      if (tags.includes(filterValue)) {

        matchingActors.push({
          country,
          actor
        });

      }

    });

  }
);


  const actorCards =
    matchingActors.map(
      ({ country, actor }) => `

        <button
          type="button"
          class="coalition-actor-card"
          data-country="${country}">

          <div class="coalition-actor-photo">

            ${
              actor.photo
                ? `<img
                     src="${actor.photo}"
                     alt="${actor.name}">
                   `
                : "Add photo"
            }

          </div>

          <div class="coalition-actor-name">
            ${actor.name}
          </div>

          <div class="coalition-actor-country">
            ${country}
          </div>

        </button>

      `
    ).join("");


  openModal(`

    <h2>
      ${filterValue}
    </h2>

    <div class="subtitle">
      ${
        filterType === "sector"
          ? "Sector coalition"
          : "Constituency coalition"
      }
    </div>

    <div class="coalition-actor-grid">

      ${
        actorCards
          ? actorCards
          : `
              <p class="coalition-empty">
                No actors are currently associated
                with this category.
              </p>
            `
      }

    </div>

  `);

}

