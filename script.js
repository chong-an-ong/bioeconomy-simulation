/* =========================================================
   WORLD MAP
   ========================================================= */

async function loadWorldMap() {

  const mapContainer =
    document.getElementById("worldMap");


  try {

    const response =
      await fetch("assets/world.svg");


    if (!response.ok) {

      throw new Error(
        `Could not load world.svg: ${response.status}`
      );

    }


    const svgText =
      await response.text();


    mapContainer.innerHTML =
      svgText;


    const svg =
      mapContainer.querySelector("svg");


    if (!svg) {

      throw new Error(
        "world.svg does not contain an SVG element."
      );

    }


    svg.id =
      "worldMapSvg";


    svg.removeAttribute("width");
    svg.removeAttribute("height");


    svg.setAttribute(
      "width",
      "100%"
    );

    svg.setAttribute(
      "height",
      "100%"
    );

    svg.setAttribute(
      "preserveAspectRatio",
      "xMidYMid meet"
    );


    attachCountryHandlers();

    /*
      The selector is independent of the SVG,
      so it can be created immediately after
      the map has loaded.
    */

    createCountrySelector();


  } catch (error) {

    console.error(
      "Error loading world map:",
      error
    );


    mapContainer.innerHTML =
      '<p style="color: white;">Unable to load world map.</p>';

  }

}


/* =========================================================
   MAP COUNTRY HANDLERS
   ========================================================= */

function attachCountryHandlers() {

  const countryMap = {

    IN: "India",
    BR: "Brazil",
    DE: "Germany",
    AE: "UAE",
    GA: "Gabon",
    FI: "Finland"

  };


  const classCountryMap = {

    Indonesia: "Indonesia",
    Australia: "Australia"

  };


  /* -------------------------------------------------------
     Clear map hover
     ------------------------------------------------------- */

  function clearHover() {

    document
      .querySelectorAll(
        "#worldMapSvg .country.country-hover"
      )
      .forEach(country => {

        country.classList.remove(
          "country-hover"
        );

      });

  }


  /* -------------------------------------------------------
     Single-path countries
     ------------------------------------------------------- */

  Object.entries(countryMap)
    .forEach(([isoCode, countryName]) => {

      const country =
        document.getElementById(isoCode);


      if (!country) {

        console.warn(
          `Could not find ${isoCode} in world.svg`
        );

        return;

      }


      country.classList.add(
        "country"
      );

      country.dataset.countryName =
        countryName;


      /* Hover */

      country.addEventListener(
        "mouseenter",
        () => {

          country.classList.add(
            "country-hover"
          );

        }
      );


      country.addEventListener(
        "mouseleave",
        () => {

          country.classList.remove(
            "country-hover"
          );

        }
      );


      /* Click */

      country.addEventListener(
        "click",
        () => {

          selectCountry(
            countryName
          );

          openDelegation(
            countryName
          );

        }
      );

    });


  /* -------------------------------------------------------
     Multi-path countries
     ------------------------------------------------------- */

  Object.entries(classCountryMap)
    .forEach(([svgClass, countryName]) => {

      const countryPaths =
        Array.from(
          document.querySelectorAll(
            `#worldMapSvg path.${svgClass}`
          )
        );


      if (!countryPaths.length) {

        console.warn(
          `Could not find ${svgClass} in world.svg`
        );

        return;

      }


      countryPaths.forEach(country => {

        country.classList.add(
          "country"
        );

        country.dataset.countryName =
          countryName;

        country.dataset.countryGroup =
          svgClass;


        /* Hover entire country */

        country.addEventListener(
          "mouseenter",
          () => {

            countryPaths.forEach(c => {

              c.classList.add(
                "country-hover"
              );

            });

          }
        );


        country.addEventListener(
          "mouseleave",
          () => {

            countryPaths.forEach(c => {

              c.classList.remove(
                "country-hover"
              );

            });

          }
        );


        /* Click any piece */

        country.addEventListener(
          "click",
          () => {

            selectCountry(
              countryName
            );

            openDelegation(
              countryName
            );

          }
        );

      });

    });


  /* -------------------------------------------------------
     Selector ↔ map hover synchronization
     ------------------------------------------------------- */

  document.addEventListener(
    "mouseenter",
    event => {

      const button =
        event.target.closest(
          ".country-selector-button"
        );


      if (!button) {
        return;
      }


      clearHover();

      highlightCountry(
        button.dataset.country
      );

    },
    true
  );


  document.addEventListener(
    "mouseleave",
    event => {

      const button =
        event.target.closest(
          ".country-selector-button"
        );


      if (!button) {
        return;
      }


      clearHover();

    },
    true
  );

}


