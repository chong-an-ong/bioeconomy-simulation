function openTreatyCategory(category) {

  const items =
    treatyHub[category] || [];


  const itemsHTML =
  items.length

    ? items.map((item, index) => {

        /* Subsection heading */

        if (item.type === "section") {

          return `
            <div class="treaty-section">
              ${item.title}
            </div>
          `;

        }


        /* Country heading only if different from previous item */

        const previousItem =
          items[index - 1];

        const showCountry =
          item.country &&
          (
            !previousItem ||
            previousItem.country !== item.country
          );


        return `
          <div class="treaty-item">

            ${
              showCountry
                ? `
                  <div class="treaty-country">
                    ${countryFlags[item.country] || ""} ${item.country}
                  </div>
                `
                : ""
            }

            <a
              class="treaty-link"
              href="${item.url}"
              target="_blank"
              rel="noopener">

              ${item.title}

            </a>

          </div>
        `;

      }).join("")

    : `

        <p>
          No documents have been added yet.
        </p>

      `;


  openModal(`

    <button
      type="button"
      class="treaty-back-button"
      id="treatyBackButton">

      ← Treaty Hub

    </button>

    <h2>
      ${category}
    </h2>

    <div class="subtitle">
      Documents and reference materials
    </div>

    <div class="treaty-document-list">

      ${itemsHTML}

    </div>

  `);

}
